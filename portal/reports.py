"""Builds a student's term report as a standalone HTML page."""


def render_report(student, marks):
    rows = "\n".join(
        f"      <tr><td>{m['subject']}</td><td>{m['term']}</td><td>{m['score']}</td></tr>"
        for m in marks
    )
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <title>Term report - {student['full_name']}</title>
  <style>
    body {{ font-family: Georgia, serif; color: #1f2937; margin: 2rem; }}
    h1 {{ color: #14532d; }}
    table {{ border-collapse: collapse; width: 100%; margin-top: 1rem; }}
    th, td {{ border: 1px solid #ccc; padding: .4rem .6rem; text-align: left; }}
    .remark {{ margin-top: 1.5rem; font-style: italic; }}
    footer {{ margin-top: 2rem; color: #6b7280; font-size: .8rem; }}
  </style>
</head>
<body>
  <h1>Mfano High School - Term Report</h1>
  <p><strong>{student['full_name']}</strong> ({student['admission']})
     &middot; {student['form']} {student['stream']}</p>
  <p>Fee balance: KES {student['fee_balance']:,}</p>
  <table>
    <thead><tr><th>Subject</th><th>Term</th><th>Score</th></tr></thead>
    <tbody>
{rows}
    </tbody>
  </table>
  <p class="remark">Class teacher's remark: {student['remark']}</p>
  <footer>
    Generated by the Mfano reporting tool.
    <!-- legacy ops console (not yet secured): /ops/students -->
  </footer>
</body>
</html>
"""
